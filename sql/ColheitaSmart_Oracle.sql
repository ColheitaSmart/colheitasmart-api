PROMPT === 1. Criacao das tabelas e sequences ===
CREATE TABLE TB_AGRICULTOR (
    CD_AGRICULTOR NUMBER(19),
    NM_AGRICULTOR VARCHAR2(100 CHAR) NOT NULL,
    DS_EMAIL VARCHAR2(150 CHAR) NOT NULL,
    NR_TELEFONE VARCHAR2(20 CHAR) NOT NULL,
    NM_CIDADE VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT PK_AGRICULTOR PRIMARY KEY (CD_AGRICULTOR),
    CONSTRAINT UK_AGRICULTOR_EMAIL UNIQUE (DS_EMAIL)
);
COMMENT ON TABLE TB_AGRICULTOR IS 'Pequeno produtor responsavel pelos lotes.';
CREATE SEQUENCE SQ_TB_AGRICULTOR START WITH 1 INCREMENT BY 1;

CREATE TABLE TB_CULTURA (
    CD_CULTURA NUMBER(19),
    NM_CULTURA VARCHAR2(100 CHAR) NOT NULL,
    DS_CATEGORIA VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT PK_CULTURA PRIMARY KEY (CD_CULTURA)
);
COMMENT ON TABLE TB_CULTURA IS 'Catalogo de culturas agricolas acompanhadas.';
CREATE SEQUENCE SQ_TB_CULTURA START WITH 1 INCREMENT BY 1;

CREATE TABLE TB_INSUMO (
    CD_INSUMO NUMBER(19),
    NM_INSUMO VARCHAR2(100 CHAR) NOT NULL,
    DS_UNIDADE VARCHAR2(30 CHAR) NOT NULL,
    CONSTRAINT PK_INSUMO PRIMARY KEY (CD_INSUMO)
);
COMMENT ON TABLE TB_INSUMO IS 'Catalogo de materiais utilizados no manejo pos-colheita.';
CREATE SEQUENCE SQ_TB_INSUMO START WITH 1 INCREMENT BY 1;

CREATE TABLE TB_LOTE (
    CD_LOTE NUMBER(19),
    CD_AGRICULTOR NUMBER(19) NOT NULL,
    CD_CULTURA NUMBER(19) NOT NULL,
    QT_PESO_INICIAL_KG NUMBER(13,3) NOT NULL,
    QT_PESO_DISPONIVEL_KG NUMBER(13,3) NOT NULL,
    DT_COLHEITA DATE NOT NULL,
    DS_ARMAZENAMENTO VARCHAR2(200 CHAR) NOT NULL,
    VL_PRECO_KG NUMBER(12,2) NOT NULL,
    DS_STATUS VARCHAR2(20 CHAR) NOT NULL,
    CONSTRAINT PK_LOTE PRIMARY KEY (CD_LOTE),
    CONSTRAINT FK_LOTE_AGRICULTOR FOREIGN KEY (CD_AGRICULTOR) REFERENCES TB_AGRICULTOR (CD_AGRICULTOR),
    CONSTRAINT FK_LOTE_CULTURA FOREIGN KEY (CD_CULTURA) REFERENCES TB_CULTURA (CD_CULTURA),
    CONSTRAINT CK_LOTE_INICIAL CHECK (QT_PESO_INICIAL_KG > 0),
    CONSTRAINT CK_LOTE_DISPONIVEL CHECK (QT_PESO_DISPONIVEL_KG BETWEEN 0 AND QT_PESO_INICIAL_KG),
    CONSTRAINT CK_LOTE_PRECO CHECK (VL_PRECO_KG >= 0),
    CONSTRAINT CK_LOTE_STATUS CHECK (DS_STATUS IN ('DISPONIVEL', 'ESGOTADO', 'ENCERRADO'))
);
COMMENT ON TABLE TB_LOTE IS 'Lote colhido e acompanhado pelo produtor.';
CREATE SEQUENCE SQ_TB_LOTE START WITH 1 INCREMENT BY 1;
CREATE INDEX IX_LOTE_AGRICULTOR ON TB_LOTE (CD_AGRICULTOR);
CREATE INDEX IX_LOTE_CULTURA ON TB_LOTE (CD_CULTURA);

CREATE TABLE TB_MONITORAMENTO (
    CD_MONITORAMENTO NUMBER(19),
    CD_LOTE NUMBER(19) NOT NULL,
    DT_MONITORAMENTO DATE NOT NULL,
    VL_TEMPERATURA NUMBER(5,2),
    DS_CONDICAO VARCHAR2(100 CHAR) NOT NULL,
    DS_OBSERVACAO VARCHAR2(300 CHAR),
    CONSTRAINT PK_MONITORAMENTO PRIMARY KEY (CD_MONITORAMENTO),
    CONSTRAINT FK_MONITORAMENTO_LOTE FOREIGN KEY (CD_LOTE) REFERENCES TB_LOTE (CD_LOTE)
);
COMMENT ON TABLE TB_MONITORAMENTO IS 'Historico de observacoes sobre armazenamento e condicao dos lotes.';
CREATE SEQUENCE SQ_TB_MONITORAMENTO START WITH 1 INCREMENT BY 1;
CREATE INDEX IX_MONITORAMENTO_LOTE ON TB_MONITORAMENTO (CD_LOTE);

CREATE TABLE TB_PREVISAO (
    CD_PREVISAO NUMBER(19),
    CD_LOTE NUMBER(19) NOT NULL,
    DT_PREVISAO DATE NOT NULL,
    DS_NIVEL_RISCO VARCHAR2(20 CHAR) NOT NULL,
    VL_PERDA_ESTIMADA_KG NUMBER(13,3),
    DS_MODELO VARCHAR2(100 CHAR) NOT NULL,
    CONSTRAINT PK_PREVISAO PRIMARY KEY (CD_PREVISAO),
    CONSTRAINT FK_PREVISAO_LOTE FOREIGN KEY (CD_LOTE) REFERENCES TB_LOTE (CD_LOTE),
    CONSTRAINT CK_PREVISAO_RISCO CHECK (DS_NIVEL_RISCO IN ('BAIXO', 'MEDIO', 'ALTO')),
    CONSTRAINT CK_PREVISAO_PERDA CHECK (VL_PERDA_ESTIMADA_KG >= 0)
);
COMMENT ON TABLE TB_PREVISAO IS 'Historico de estimativas de risco de perda dos lotes.';
CREATE SEQUENCE SQ_TB_PREVISAO START WITH 1 INCREMENT BY 1;
CREATE INDEX IX_PREVISAO_LOTE ON TB_PREVISAO (CD_LOTE);

CREATE TABLE TB_VENDA (
    CD_VENDA NUMBER(19),
    CD_LOTE NUMBER(19) NOT NULL,
    DT_VENDA DATE NOT NULL,
    QT_VENDIDA_KG NUMBER(13,3) NOT NULL,
    VL_PRECO_KG NUMBER(12,2) NOT NULL,
    VL_TOTAL NUMBER(23,2) NOT NULL,
    CONSTRAINT PK_VENDA PRIMARY KEY (CD_VENDA),
    CONSTRAINT FK_VENDA_LOTE FOREIGN KEY (CD_LOTE) REFERENCES TB_LOTE (CD_LOTE),
    CONSTRAINT CK_VENDA_QUANTIDADE CHECK (QT_VENDIDA_KG > 0),
    CONSTRAINT CK_VENDA_PRECO CHECK (VL_PRECO_KG >= 0),
    CONSTRAINT CK_VENDA_TOTAL CHECK (VL_TOTAL = ROUND(QT_VENDIDA_KG * VL_PRECO_KG, 2))
);
COMMENT ON TABLE TB_VENDA IS 'Vendas efetivamente registradas para os lotes.';
CREATE SEQUENCE SQ_TB_VENDA START WITH 1 INCREMENT BY 1;
CREATE INDEX IX_VENDA_LOTE ON TB_VENDA (CD_LOTE);

CREATE TABLE TB_PERDA (
    CD_PERDA NUMBER(19),
    CD_LOTE NUMBER(19) NOT NULL,
    DT_PERDA DATE NOT NULL,
    QT_PERDIDA_KG NUMBER(13,3) NOT NULL,
    DS_MOTIVO VARCHAR2(200 CHAR) NOT NULL,
    CONSTRAINT PK_PERDA PRIMARY KEY (CD_PERDA),
    CONSTRAINT FK_PERDA_LOTE FOREIGN KEY (CD_LOTE) REFERENCES TB_LOTE (CD_LOTE),
    CONSTRAINT CK_PERDA_QUANTIDADE CHECK (QT_PERDIDA_KG > 0)
);
COMMENT ON TABLE TB_PERDA IS 'Perdas de produto registradas apos a colheita.';
CREATE SEQUENCE SQ_TB_PERDA START WITH 1 INCREMENT BY 1;
CREATE INDEX IX_PERDA_LOTE ON TB_PERDA (CD_LOTE);

CREATE TABLE TB_LOTE_INSUMO (
    CD_LOTE NUMBER(19),
    CD_INSUMO NUMBER(19),
    QT_UTILIZADA NUMBER(13,3) NOT NULL,
    CONSTRAINT PK_LOTE_INSUMO PRIMARY KEY (CD_LOTE, CD_INSUMO),
    CONSTRAINT FK_LOTE_INSUMO_LOTE FOREIGN KEY (CD_LOTE) REFERENCES TB_LOTE (CD_LOTE),
    CONSTRAINT FK_LOTE_INSUMO_INSUMO FOREIGN KEY (CD_INSUMO) REFERENCES TB_INSUMO (CD_INSUMO),
    CONSTRAINT CK_LOTE_INSUMO_QT CHECK (QT_UTILIZADA > 0)
);
COMMENT ON TABLE TB_LOTE_INSUMO IS 'Associacao entre os lotes e os insumos utilizados.';
CREATE INDEX IX_LOTE_INSUMO_INSUMO ON TB_LOTE_INSUMO (CD_INSUMO);

