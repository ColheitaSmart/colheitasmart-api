-- Quanto vale o estoque disponivel de cada lote ao preco atual?
SELECT CD_LOTE, QT_PESO_DISPONIVEL_KG, VL_PRECO_KG,
       ROUND(QT_PESO_DISPONIVEL_KG * VL_PRECO_KG, 2) AS VL_ESTOQUE
FROM TB_LOTE
WHERE DS_STATUS = 'DISPONIVEL'
ORDER BY VL_ESTOQUE DESC, CD_LOTE;

PROMPT Consulta 03
-- A qual agricultor e cultura pertence cada lote?
SELECT TB_LOTE.CD_LOTE, TB_AGRICULTOR.NM_AGRICULTOR, TB_CULTURA.NM_CULTURA
FROM TB_LOTE
INNER JOIN TB_AGRICULTOR ON TB_LOTE.CD_AGRICULTOR = TB_AGRICULTOR.CD_AGRICULTOR
INNER JOIN TB_CULTURA ON TB_LOTE.CD_CULTURA = TB_CULTURA.CD_CULTURA
ORDER BY TB_LOTE.CD_LOTE;

PROMPT Consulta 04
-- Quantos lotes cada agricultor tem, incluindo quem ainda nao cadastrou nenhum?
SELECT TB_AGRICULTOR.CD_AGRICULTOR, TB_AGRICULTOR.NM_AGRICULTOR,
       COUNT(TB_LOTE.CD_LOTE) AS QT_LOTES
FROM TB_AGRICULTOR
LEFT JOIN TB_LOTE ON TB_AGRICULTOR.CD_AGRICULTOR = TB_LOTE.CD_AGRICULTOR
GROUP BY TB_AGRICULTOR.CD_AGRICULTOR, TB_AGRICULTOR.NM_AGRICULTOR
ORDER BY QT_LOTES DESC, TB_AGRICULTOR.CD_AGRICULTOR;

PROMPT Consulta 05
-- Quais culturas ja tem lotes cadastrados e quais ainda estao sem lote?
SELECT TB_CULTURA.CD_CULTURA, TB_CULTURA.NM_CULTURA, COUNT(TB_LOTE.CD_LOTE) AS QT_LOTES
FROM TB_LOTE
RIGHT JOIN TB_CULTURA ON TB_LOTE.CD_CULTURA = TB_CULTURA.CD_CULTURA
GROUP BY TB_CULTURA.CD_CULTURA, TB_CULTURA.NM_CULTURA
ORDER BY QT_LOTES DESC, TB_CULTURA.CD_CULTURA;

PROMPT Consulta 06
-- Quanto cada agricultor arrecadou com as vendas registradas?
SELECT TB_AGRICULTOR.CD_AGRICULTOR, TB_AGRICULTOR.NM_AGRICULTOR,
       SUM(TB_VENDA.VL_TOTAL) AS VL_RECEITA
FROM TB_AGRICULTOR
INNER JOIN TB_LOTE ON TB_AGRICULTOR.CD_AGRICULTOR = TB_LOTE.CD_AGRICULTOR
INNER JOIN TB_VENDA ON TB_LOTE.CD_LOTE = TB_VENDA.CD_LOTE
GROUP BY TB_AGRICULTOR.CD_AGRICULTOR, TB_AGRICULTOR.NM_AGRICULTOR
ORDER BY VL_RECEITA DESC, TB_AGRICULTOR.CD_AGRICULTOR;

PROMPT Consulta 07
-- Qual foi a temperatura media, minima e maxima registrada por lote?
SELECT CD_LOTE, ROUND(AVG(VL_TEMPERATURA), 2) AS VL_MEDIA,
       MIN(VL_TEMPERATURA) AS VL_MINIMA, MAX(VL_TEMPERATURA) AS VL_MAXIMA
FROM TB_MONITORAMENTO
WHERE VL_TEMPERATURA IS NOT NULL
GROUP BY CD_LOTE
ORDER BY CD_LOTE;

PROMPT Consulta 08
-- Quais lotes tiveram mais de 10 kg de perda acumulada?
SELECT CD_LOTE, SUM(QT_PERDIDA_KG) AS QT_PERDA_KG
FROM TB_PERDA
GROUP BY CD_LOTE
HAVING SUM(QT_PERDIDA_KG) > 10
ORDER BY QT_PERDA_KG DESC, CD_LOTE;

PROMPT Consulta 09
-- Quais previsoes por lote apontam perda estimada acima da media registrada?
SELECT CD_PREVISAO, CD_LOTE, DT_PREVISAO, DS_NIVEL_RISCO, VL_PERDA_ESTIMADA_KG
FROM TB_PREVISAO
WHERE VL_PERDA_ESTIMADA_KG > (
    SELECT AVG(VL_PERDA_ESTIMADA_KG)
    FROM TB_PREVISAO
)
ORDER BY VL_PERDA_ESTIMADA_KG DESC, CD_PREVISAO;

PROMPT Consulta 10
-- Quais insumos foram usados em cada lote e em qual quantidade?
SELECT TB_LOTE_INSUMO.CD_LOTE, TB_INSUMO.NM_INSUMO,
       TB_LOTE_INSUMO.QT_UTILIZADA, TB_INSUMO.DS_UNIDADE
FROM TB_LOTE_INSUMO
INNER JOIN TB_INSUMO ON TB_LOTE_INSUMO.CD_INSUMO = TB_INSUMO.CD_INSUMO
ORDER BY TB_LOTE_INSUMO.CD_LOTE, TB_INSUMO.NM_INSUMO;

